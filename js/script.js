// Этот файл содержит JavaScript-код для интерактивных элементов сайта.
// Основная функция - управление отображением мобильного навигационного меню.
// =================================================================================================

// Добавляем обработчик события, который сработает после полной загрузки DOM-дерева.
// Это гарантирует, что все HTML-элементы будут доступны для манипуляций.
document.addEventListener('DOMContentLoaded', () => {
    // Находим кнопку переключения меню по ее классу.
    const menuToggle = document.querySelector('.menu-toggle');
    // Находим навигационное меню.
    const nav = document.querySelector('header nav');

    // Проверяем, что оба элемента (кнопка и меню) существуют на странице,
    // чтобы избежать ошибок, если они отсутствуют.
    if (menuToggle && nav) {
        // Добавляем обработчик события 'click' на кнопку.
        menuToggle.addEventListener('click', () => {
            // При каждом клике переключаем класс 'active' у навигационного меню.
            // Класс 'active' (определенный в CSS) делает меню видимым.
            nav.classList.toggle('active');
        });
    }
});
